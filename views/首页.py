st.markdown(
    """
你这个感觉是对的，而且值得认真回答一下。

**为什么它们被放在一起**：这两块看着不搭，底层其实是同一套东西——
「地图 + 空间数据 + 可视化交互」。底图、坐标系、热力/聚合/图层叠加这些能力，
住房和徒步都要用。所以它们共用一个 `app_utils.py`、一套底图、一套异常兜底，
新增页面的边际成本很低，这也是它们被塞进同一个站点的技术原因。

**但从"产品"角度看，它们确实是两个产品**：受众不重叠、使用场景不重叠、
连数据都不共享。放在一起的代价是——新用户点进来会懵：这到底是给地产看的还是给驴友看的？

所以现在用侧边栏分组把边界划清楚（「地理空间工具」/「户外徒步」）。
如果你要往正式产品做，我的建议是：

| 方案 | 做法 | 适合 |
| --- | --- | --- |
| A. 保持一个站点 + 分组（当前） | 侧边栏两组，首页说清楚定位 | 个人作品集、演示、自己用 |
| B. 拆成两个站点 | 复制仓库，一个只留 7 个地图页，一个只留徒步 | 想分别给不同人看 |
| C. 只留一条主线 | 选定一个方向（比如徒步），另一个砍掉 | 想做成一个"正经产品" |

我的推荐是 **B**：两边的代码已经解耦（共用 `app_utils.py` 和 `data/`），
拆开只需要删页面、改导航，半小时的事。需要我拆可以直接说。
"""
)

