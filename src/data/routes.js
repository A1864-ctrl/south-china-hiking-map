function hoursOf(km, climb) {
  const h = km / 3.2 + climb / 500
  if (h > 12) return '2 天'
  if (h > 9) return '8-10 小时'
  if (h > 7) return '6-8 小时'
  if (h > 5) return '4-6 小时'
  return '2-4 小时'
}

