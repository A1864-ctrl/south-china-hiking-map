/** 取某条路线的科普内容 */
export function ecologyOf(route) {
  const region = REGIONS[`${route.province}|${route.city}`] || null
  const famKey = TERRAIN_FAMILY[route.terrain] || 'granite'
  const terrain = TERRAIN[famKey]
  const ov = OVERRIDE[route.id] || {}

  const animals = []
  const seen = new Set()
  for (const a of [...(ov.animals || []), ...(region ? region.animals : []), ...(terrain.animals || [])]) {
    if (seen.has(a.n)) continue
    seen.add(a.n)
    animals.push(a)
  }

  // 关键地形节点：从途经点里挑有说明的，最多 5 个
  const keyPoints = (route.waypoints || [])
    .filter((p) => p.note)
    .slice(0, 5)
    .map((p) => ({ name: p.name, ele: p.ele, note: p.note }))

  // 合并时去掉重复项：短词（如「大风」）已被长句覆盖就不再单列
  const cautions = []
  const add = (t) => {
    const v = String(t || '').trim()
    if (!v) return
    if (cautions.some((x) => x === v || (v.length <= 6 && x.includes(v)))) return
    cautions.push(v)
  }
  for (const t of ov.cautions || []) add(t)
  for (const t of terrain.hazard) add(t)
  for (const t of region ? region.notes : []) add(t)

  return {
    found: !!region,
    region: region ? region.name : `${route.province} · ${route.city}`,
    regionGeo: region ? region.geo : '该区域暂无独立档案，以下按地貌类型给出通用科普。',
    bands: region ? region.bands : [],
    terrain,
    animals: animals.slice(0, 8),
    keyPoints,
    cautions,
    risks: route.risk || [],
    fact: ov.fact || '',
    facts: {
      ele: `${route.minEle}–${route.maxEle} m`,
      range: `${route.distance} km / ↑${route.climb} m`,
      season: route.season,
      terrain: route.terrain
    }
  }
}
