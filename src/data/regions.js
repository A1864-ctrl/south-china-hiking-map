/** 省份 → 城市列表 */
export function citiesOf(province) {
  const hit = REGIONS.find((r) => r.p === province)
  return hit ? hit.c : []
}

/** 展示用短名：广东省深圳市 → 广东·深圳 */
export function regionShort(province, city) {
  if (!province && !city) return ''
  const p = (province || '').replace(/(省|市|壮族自治区|回族自治区|维吾尔自治区|特别行政区|自治区)$/, '')
  return city && city !== p ? `${p}·${city}` : p
}
